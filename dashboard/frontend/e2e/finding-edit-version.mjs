import { expect } from '@playwright/test'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'

export async function verifyFindingEditVersion(page, testInfo, workspace) {
  const id = 'finding-version'
  expect((await page.request.post('/api/v1/engagements', { data: { name: id, domain: 'example.test', type: 'engagement' } })).ok()).toBe(true)
  const created = await page.request.post(`/api/v1/findings/${id}`, { data: { slug: 'versioned', title: 'Ficha original', status: 'CANDIDATE' } })
  expect(created.status()).toBe(200)
  const first = await created.json()
  const path = `${workspace}/engagements/${id}/evidence/versioned.md`
  const scope = await readFile(`${workspace}/engagements/${id}/target.yaml`)
  expect(first.source_sha256).toBe(createHash('sha256').update(await readFile(path)).digest('hex'))
  await page.goto(`/engagements/engagement/${id}`)
  await page.getByRole('button', { name: /Hallazgos \(evidence\/\)/ }).click()
  await page.getByRole('button', { name: 'Editar', exact: true }).click()
  const editor = page.getByTestId('finding-markdown')
  const draft = '## Mi revisión\nBorrador que debe conservarse ante conflicto.'
  await editor.fill(draft)
  const updated = await page.request.post(`/api/v1/findings/${id}`, { data: { slug: first.slug, title: 'Título actualizado en otra vista',
    body: 'Cambio guardado por otra vista.', finding_id: first.finding_id, expected_source_sha256: first.source_sha256 } })
  expect(updated.status()).toBe(200)
  const latest = await updated.json()
  const before = await readFile(path)
  const response = page.waitForResponse(r => r.url().includes(`/findings/${id}`) && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Guardar Ficha', exact: true }).click()
  expect((await response).status()).toBe(409)
  await expect(page.getByTestId('finding-save-error')).toContainText('La ficha cambió')
  await expect(editor).toHaveValue(draft)
  expect(await readFile(path)).toEqual(before)
  await page.getByRole('button', { name: 'Ver ficha actual sin reemplazar borrador', exact: true }).click()
  const comparison = page.getByTestId('finding-current-version')
  await expect(comparison).toContainText(latest.frontmatter.title)
  await expect(comparison).toContainText(latest.body)
  await expect(comparison).toContainText(latest.source_sha256)
  await expect(editor).toHaveValue(draft)
  await comparison.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('finding-edit-conflict-comparison.png'), fullPage: true })
  await page.getByRole('button', { name: 'Revisé los cambios; usar esta versión como base', exact: true }).click()
  expect(await readFile(path)).toEqual(before)
  await expect(editor).toHaveValue(draft)
  const saved = page.waitForResponse(r => r.url().includes(`/findings/${id}`) && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Guardar Ficha', exact: true }).click()
  expect((await saved).status()).toBe(200)
  await expect(editor).toHaveCount(0)
  const final = await (await page.request.get(`/api/v1/findings/${id}/${first.slug}`)).json()
  expect(final.body).toBe(draft)
  expect(final.finding_id).toBe(first.finding_id)
  expect(final.source_sha256).toBe(createHash('sha256').update(await readFile(path)).digest('hex'))
  expect(final.source_sha256).not.toBe(latest.source_sha256)
  await page.reload()
  await page.getByRole('button', { name: /Hallazgos \(evidence\/\)/ }).click()
  await page.getByRole('button', { name: 'Editar', exact: true }).click()
  await expect(editor).toHaveValue(draft)
  await page.screenshot({ path: testInfo.outputPath('finding-edit-version-saved.png'), fullPage: true })
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  const changed = await page.request.post(`/api/v1/findings/${id}`, { data: { slug: first.slug, title: 'Revisión posterior al listado', body: 'No borrar sin leer', expected_source_sha256: final.source_sha256 } })
  expect(changed.status()).toBe(200)
  const replacement = await changed.json()
  const preserved = await readFile(path)
  page.once('dialog', dialog => dialog.accept())
  const rejectedDelete = page.waitForResponse(r => r.url().includes(`/findings/${id}/${first.slug}`) && r.request().method() === 'DELETE')
  await page.getByRole('button', { name: 'Eliminar', exact: true }).click()
  expect((await rejectedDelete).status()).toBe(409)
  await expect(page.getByTestId('finding-delete-error')).toContainText('no se eliminó')
  expect(await readFile(path)).toEqual(preserved)
  await page.screenshot({ path: testInfo.outputPath('finding-delete-conflict.png'), fullPage: true })
  await page.getByRole('button', { name: 'Recargar fichas para revisar antes de eliminar', exact: true }).click()
  await expect(page.getByRole('heading', { name: replacement.frontmatter.title, exact: true })).toBeVisible()
  expect(await readFile(path)).toEqual(preserved)
  page.once('dialog', dialog => dialog.accept())
  const acceptedDelete = page.waitForResponse(r => r.url().includes(`/findings/${id}/${first.slug}`) && r.request().method() === 'DELETE')
  await page.getByRole('button', { name: 'Eliminar', exact: true }).click()
  expect((await acceptedDelete).status()).toBe(200)
  await expect(page.getByRole('heading', { name: replacement.frontmatter.title, exact: true })).toHaveCount(0)
  expect((await page.request.get(`/api/v1/findings/${id}/${first.slug}`)).status()).toBe(404)
  expect(await readFile(`${workspace}/engagements/${id}/target.yaml`)).toEqual(scope)
  expect((await (await page.request.get(`/api/v1/recon/${id}/history`)).json()).jobs).toEqual([])
}
